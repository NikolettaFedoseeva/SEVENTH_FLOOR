export const getPropertyLabel = (
  category: string,
  value?: string | string[],
): string => {
  if (!value) return "—";
  if (Array.isArray(value)) {
    return value.map((v) => propertyDictionary[category]?.[v] || v).join(", ");
  }
  return propertyDictionary[category]?.[value] || value;
};
